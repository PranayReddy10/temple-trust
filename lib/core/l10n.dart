/// The globe button that opens the language picker; on the home screens.
class LanguageButton extends StatelessWidget {
  const LanguageButton({super.key, this.color});

  final Color? color;

  @override
  Widget build(BuildContext context) {
    final s = S.of(context);
    final code = Localizations.localeOf(context).languageCode;
    return Tooltip(
      message: s('language'),
      child: InkWell(
        borderRadius: BorderRadius.circular(999),
        onTap: () => showLanguageSheet(context),
        child: Container(
          padding: const EdgeInsets.fromLTRB(10, 6, 12, 6),
          decoration: BoxDecoration(
            borderRadius: BorderRadius.circular(999),
            border: Border.all(
                color: (color ?? Theme.of(context).colorScheme.onSurface)
                    .withValues(alpha: 0.35)),
          ),
          child: Row(mainAxisSize: MainAxisSize.min, children: [
            Icon(Icons.translate, size: 18, color: color),
            const SizedBox(width: 6),
            Text(AppLanguage.byCode(code).nativeName,
                style: TextStyle(
                    color: color, fontWeight: FontWeight.w700, fontSize: 13)),
          ]),
        ),
      ),
    );
  }
}

/// The language picker. Works without a [LocaleController] in the tree (as
/// in tests), where it simply shows the list.
Future<void> showLanguageSheet(BuildContext context) {
  final s = S.of(context);
  final current = Localizations.localeOf(context).languageCode;
  LocaleController? controller;
  try {
    controller = context.read<LocaleController>();
  } catch (_) {
    controller = null;
  }
  return showModalBottomSheet<void>(
    context: context,
    showDragHandle: true,
    builder: (c) {
      final theme = Theme.of(c);
      return SafeArea(
        child: SingleChildScrollView(
          padding: const EdgeInsets.fromLTRB(20, 0, 20, 20),
          child: Column(
              mainAxisSize: MainAxisSize.min,
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Text(s('choose_language'), style: theme.textTheme.titleLarge),
                const SizedBox(height: 4),
                Text(s('language_note'), style: theme.textTheme.bodySmall),
                const SizedBox(height: 14),
                for (final l in AppLanguage.all)
                  Padding(
                    padding: const EdgeInsets.only(bottom: 8),
                    child: Material(
                      color: l.code == current
                          ? theme.colorScheme.primary.withValues(alpha: 0.1)
                          : theme.colorScheme.surfaceContainerHighest,
                      borderRadius: BorderRadius.circular(14),
                      child: InkWell(
                        borderRadius: BorderRadius.circular(14),
                        onTap: () {
                          controller?.set(l.code);
                          Navigator.pop(c);
                        },
                        child: Padding(
                          padding: const EdgeInsets.symmetric(
                              horizontal: 16, vertical: 12),
                          child: Row(children: [
                            Expanded(
                              child: Column(
                                  crossAxisAlignment: CrossAxisAlignment.start,
                                  children: [
                                    Text(l.nativeName,
                                        style: theme.textTheme.titleMedium),
                                    if (l.name != l.nativeName)
                                      Text(l.name,
                                          style: theme.textTheme.bodySmall),
                                  ]),
                            ),
                            if (l.code == current)
                              Icon(Icons.check_circle,
                                  color: theme.colorScheme.primary),
                          ]),
                        ),
                      ),
                    ),
                  ),
              ]),
        ),
      );
    },
  );
}
